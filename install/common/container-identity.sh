#!/usr/bin/env bash
# Install a visible identity before the container starts application services.
set -Eeuo pipefail

# An alternate filesystem root supports isolated validation without touching /etc.
identity_root="${1:-/}"
identity_root="${identity_root%/}"

case "${RFFUSION_ENV:-}" in
    production) identity_label="PRODUÇÃO"; identity_color="31" ;;
    development) identity_label="DEV"; identity_color="32" ;;
    *) printf 'ERROR: Missing or invalid RFFUSION_ENV.\n' >&2; exit 1 ;;
esac
case "${RFFUSION_COMPONENT:-}" in
    appcataloga|webfusion|mariadb) ;;
    *) printf 'ERROR: Missing or invalid RFFUSION_COMPONENT.\n' >&2; exit 1 ;;
esac

install -d "${identity_root}/etc/profile.d" "${identity_root}/etc/skel" "${identity_root}/root"
printf 'RFFUSION_ENV=%s\nRFFUSION_COMPONENT=%s\n' \
    "$RFFUSION_ENV" "$RFFUSION_COMPONENT" > "${identity_root}/etc/rffusion-environment"

cat > "${identity_root}/etc/profile.d/rffusion-environment.sh" <<EOF
# Generated by the RF.Fusion container entrypoint.
export RFFUSION_ENV=${RFFUSION_ENV}
export RFFUSION_COMPONENT=${RFFUSION_COMPONENT}
case \$- in
    *i*) ;;
    *) return ;;
esac
if [[ \${TERM:-dumb} == dumb ]]; then
    PS1='[${identity_label}] \u@\h:\w\\\$ '
else
    PS1='\[\e[1;${identity_color}m\][${identity_label}]\[\e[0m\] \u@\h:\w\\\$ '
fi
EOF

# User bashrc files may reset PS1 after /etc/bash.bashrc; source the identity last.
identity_hook='[ ! -r /etc/profile.d/rffusion-environment.sh ] || . /etc/profile.d/rffusion-environment.sh'
for bashrc in "${identity_root}/etc/bash.bashrc" "${identity_root}/etc/skel/.bashrc" \
    "${identity_root}/root/.bashrc" "${identity_root}"/home/*/.bashrc; do
    if [[ "$bashrc" == "${identity_root}"/home/*/.bashrc && ! -f "$bashrc" ]]; then
        continue
    fi
    if ! grep -Fqx "$identity_hook" "$bashrc" 2>/dev/null; then
        printf '\n%s\n' "$identity_hook" >> "$bashrc"
    fi
done

printf '[RF.Fusion] environment=%s component=%s\n' "$RFFUSION_ENV" "$RFFUSION_COMPONENT"
