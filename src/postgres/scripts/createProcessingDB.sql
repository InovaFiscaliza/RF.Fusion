-- PostgreSQL 17: instalação inicial em banco vazio. Execute com psql -v ON_ERROR_STOP=1.
CREATE SCHEMA "BPDATA";
SET search_path TO "BPDATA", pg_catalog;

CREATE FUNCTION "BPDATA".file_identity_sha256(value text)
RETURNS text
LANGUAGE sql
IMMUTABLE STRICT PARALLEL SAFE
RETURN pg_catalog.encode(pg_catalog.sha256(pg_catalog.convert_to(value, 'UTF8')), 'hex');

CREATE TABLE "HOST" (
  "ID_HOST" integer NOT NULL,
  "NA_HOST_NAME" varchar(100) DEFAULT NULL,
  "NA_HOST_ADDRESS" varchar(50) DEFAULT NULL,
  "NA_HOST_PORT" integer DEFAULT NULL,
  "NA_HOST_USER" varchar(50) DEFAULT NULL,
  "NA_HOST_PASSWORD" varchar(50) DEFAULT NULL,
  "DT_LAST_BACKUP" timestamp without time zone DEFAULT NULL,
  "DT_LAST_PROCESSING" timestamp without time zone DEFAULT NULL,
  "DT_LAST_DISCOVERY" timestamp without time zone DEFAULT NULL,
  "IS_OFFLINE" smallint DEFAULT 0,
  "IS_BUSY" smallint DEFAULT 0,
  "NU_PID" integer DEFAULT 0,
  "DT_LAST_FAIL" timestamp without time zone DEFAULT NULL,
  "DT_LAST_CHECK" timestamp without time zone DEFAULT NULL,
  "DT_BUSY" timestamp without time zone DEFAULT NULL,
  "DT_LAST_OFFLINE_AT" timestamp without time zone DEFAULT NULL,
  "NA_LAST_OFFLINE_DESCRIPTION" text DEFAULT NULL,
  "NU_HOST_CHECK_ERROR" integer DEFAULT 0,
  PRIMARY KEY ("ID_HOST")
);


CREATE TABLE "HOST_TASK" (
  "ID_HOST_TASK" integer NOT NULL GENERATED BY DEFAULT AS IDENTITY,
  "FK_HOST" integer DEFAULT NULL,
  "NU_TYPE" smallint DEFAULT 0,
  "DT_HOST_TASK" timestamp without time zone DEFAULT NULL,
  "NU_STATUS" smallint DEFAULT 0,
  "NU_PID" integer DEFAULT NULL,
  "FILTER" json DEFAULT NULL,
  "NA_MESSAGE" text DEFAULT NULL,
  PRIMARY KEY ("ID_HOST_TASK"),
  CONSTRAINT "FK_HOST_TASK_HOST" FOREIGN KEY ("FK_HOST") REFERENCES "HOST" ("ID_HOST")
);
CREATE INDEX host_task_fk_host_task_host ON "HOST_TASK" ("FK_HOST");

CREATE TABLE "FILE_TASK" (
  "ID_FILE_TASK" integer NOT NULL GENERATED BY DEFAULT AS IDENTITY,
  "FK_HOST" integer DEFAULT NULL,
  "DT_FILE_TASK" timestamp without time zone DEFAULT NULL,
  "NU_TYPE" smallint DEFAULT 0,
  "NA_HOST_FILE_PATH" varchar(3000) DEFAULT NULL,
  "NA_HOST_FILE_NAME" varchar(512) DEFAULT NULL,
  "NU_HOST_FILE_MD5" varchar(32) DEFAULT NULL,
  "NA_SERVER_FILE_PATH" varchar(3000) DEFAULT NULL,
  "NA_SERVER_FILE_NAME" varchar(512) DEFAULT NULL,
  "NA_SERVER_FILE_MD5" varchar(32) DEFAULT NULL,
  "NU_STATUS" smallint DEFAULT 0,
  "NU_PID" integer DEFAULT NULL,
  "NA_EXTENSION_HOST" varchar(20) DEFAULT NULL,
  "VL_FILE_SIZE_KB_HOST" bigint DEFAULT NULL,
  "DT_FILE_CREATED_HOST" timestamp without time zone DEFAULT NULL,
  "DT_FILE_MODIFIED_HOST" timestamp without time zone DEFAULT NULL,
  "NA_EXTENSION_SERVER" varchar(20) DEFAULT NULL,
  "VL_FILE_SIZE_KB_SERVER" bigint DEFAULT NULL,
  "DT_FILE_CREATED_SERVER" timestamp without time zone DEFAULT NULL,
  "DT_FILE_MODIFIED_SERVER" timestamp without time zone DEFAULT NULL,
  "NA_MESSAGE" text DEFAULT NULL,
  "NA_ERROR_CODE" varchar(64) DEFAULT NULL,
  "NA_ERROR_DETAIL" text DEFAULT NULL,
  "NU_ERROR_CLASSIFIER_VERSION" smallint DEFAULT NULL,
  PRIMARY KEY ("ID_FILE_TASK"),
  CONSTRAINT "FK_FILE_TASK_HOST" FOREIGN KEY ("FK_HOST") REFERENCES "HOST" ("ID_HOST")
);
CREATE UNIQUE INDEX file_task_uq_fth_identity ON "FILE_TASK" ("FK_HOST", "BPDATA".file_identity_sha256("NA_HOST_FILE_PATH"), "BPDATA".file_identity_sha256("NA_HOST_FILE_NAME"));
CREATE INDEX file_task_fk_file_task_host ON "FILE_TASK" ("FK_HOST");
CREATE INDEX file_task_idx_file_task_identity ON "FILE_TASK" ("FK_HOST",(left("NA_HOST_FILE_PATH", 191)),(left("NA_HOST_FILE_NAME", 191)));
CREATE INDEX file_task_idx_file_task_queue_host ON "FILE_TASK" ("NU_STATUS","NU_TYPE","FK_HOST","ID_FILE_TASK");

CREATE TABLE "FILE_TASK_HISTORY" (
  "ID_HISTORY" integer NOT NULL GENERATED BY DEFAULT AS IDENTITY,
  "FK_HOST" integer NOT NULL,
  "DT_DISCOVERED" timestamp without time zone DEFAULT NULL,
  "DT_BACKUP" timestamp without time zone DEFAULT NULL,
  "DT_PROCESSED" timestamp without time zone DEFAULT NULL,
  "NU_STATUS_DISCOVERY" integer DEFAULT 1,
  "NU_STATUS_BACKUP" integer DEFAULT 1,
  "NU_STATUS_PROCESSING" integer DEFAULT 1,
  "NA_HOST_FILE_PATH" varchar(3000) DEFAULT NULL,
  "NA_HOST_FILE_NAME" varchar(512) DEFAULT NULL,
  "NA_SERVER_FILE_PATH" varchar(3000) DEFAULT NULL,
  "NA_SERVER_FILE_NAME" varchar(512) DEFAULT NULL,
  "VL_FILE_SIZE_KB_HOST" bigint DEFAULT NULL,
  "DT_FILE_CREATED_HOST" timestamp without time zone DEFAULT NULL,
  "DT_FILE_MODIFIED_HOST" timestamp without time zone DEFAULT NULL,
  "NA_EXTENSION_HOST" varchar(20) DEFAULT NULL,
  "VL_FILE_SIZE_KB_SERVER" bigint DEFAULT NULL,
  "DT_FILE_CREATED_SERVER" timestamp without time zone DEFAULT NULL,
  "DT_FILE_MODIFIED_SERVER" timestamp without time zone DEFAULT NULL,
  "NA_EXTENSION_SERVER" varchar(20) DEFAULT NULL,
  "NA_MESSAGE" text DEFAULT NULL,
  "NA_ERROR_CODE" varchar(64) DEFAULT NULL,
  "NA_ERROR_DETAIL" text DEFAULT NULL,
  "NU_ERROR_CLASSIFIER_VERSION" smallint DEFAULT NULL,
  "IS_PAYLOAD_DELETED" smallint NOT NULL DEFAULT 0,
  "DT_PAYLOAD_DELETED" timestamp without time zone DEFAULT NULL,
  PRIMARY KEY ("ID_HISTORY"),
  CONSTRAINT "FK_HISTORY_HOST" FOREIGN KEY ("FK_HOST") REFERENCES "HOST" ("ID_HOST")
);
CREATE UNIQUE INDEX file_task_history_uq_fth_identity ON "FILE_TASK_HISTORY" ("FK_HOST", "BPDATA".file_identity_sha256("NA_HOST_FILE_PATH"), "BPDATA".file_identity_sha256("NA_HOST_FILE_NAME"));
CREATE INDEX file_task_history_idx_fth_dedup_identity ON "FILE_TASK_HISTORY" ("FK_HOST",(left("NA_HOST_FILE_PATH", 191)),(left("NA_HOST_FILE_NAME", 191)),"VL_FILE_SIZE_KB_HOST");
CREATE INDEX file_task_history_idx_fth_host_file_name ON "FILE_TASK_HISTORY" ("NA_HOST_FILE_NAME","ID_HISTORY");
CREATE INDEX file_task_history_idx_fth_server_file_name ON "FILE_TASK_HISTORY" ("NA_SERVER_FILE_NAME","ID_HISTORY");
CREATE INDEX file_task_history_idx_fth_host_date_host ON "FILE_TASK_HISTORY" ("FK_HOST","DT_FILE_CREATED_HOST");
CREATE INDEX file_task_history_idx_fth_processed_recent ON "FILE_TASK_HISTORY" ("DT_PROCESSED","ID_HISTORY");
CREATE INDEX file_task_history_idx_fth_gc_retention ON "FILE_TASK_HISTORY" ("NU_STATUS_PROCESSING","IS_PAYLOAD_DELETED","DT_PROCESSED","ID_HISTORY");
CREATE INDEX file_task_history_idx_fth_backup_recreate ON "FILE_TASK_HISTORY" ("NU_STATUS_BACKUP","ID_HISTORY");
CREATE INDEX file_task_history_idx_fth_processing_recreate ON "FILE_TASK_HISTORY" ("NU_STATUS_BACKUP","NU_STATUS_PROCESSING","ID_HISTORY");
