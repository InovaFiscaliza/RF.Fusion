class BkpPostgresIntegrationTests(unittest.TestCase):
    """Check actual constraints, JSON adaptation, rollback, and outbox savepoints.

    Attributes:
        conninfo (str): Explicit disposable database settings, never logged.
        schema (str): Random operational schema created from the repository DDL.
        summary_schema (str): Random schema containing only the test outbox.
        handler (dbHandlerBKP): Session under test; closed after every test.
    """

    @classmethod
    def setUpClass(cls) -> None:
        """Require an isolated database and create only uniquely named test schemas.

        Args:
            None.
        Returns:
            None.
        Raises:
            unittest.SkipTest: If the explicit test connection is absent.
            ValueError: If the database name lacks the rffusion_test_ prefix.
            psycopg.Error: If creating disposable fixtures fails.
        """
        cls.conninfo = os.environ.get("RFFUSION_TEST_PG_CONNINFO", "")
        if not cls.conninfo:
            raise unittest.SkipTest("RFFUSION_TEST_PG_CONNINFO is not configured.")
        if (
            not conninfo_to_dict(cls.conninfo)
            .get("dbname", "")
            .startswith("rffusion_test_")
        ):
            raise ValueError(
                "BKP integration requires a disposable rffusion_test_* database."
            )
        suffix = uuid4().hex
        cls.schema = f"TEST_BKP_{suffix}"
        cls.summary_schema = f"TEST_SUMMARY_{suffix}"
        cls.log = MagicMock(spec=logging_utils.log)
        cls.log.pid = os.getpid()
        cls.handler = bkp_module.dbHandlerBKP(
            cls.schema, cls.log, conninfo=cls.conninfo
        )
        cls.addClassCleanup(cls._drop_schemas)
        setting = patch.object(
            bkp_module.k, "SUMMARY_DATABASE_NAME", cls.summary_schema
        )
        setting.start()
        cls.addClassCleanup(setting.stop)
        ddl_path = APP_ROOT.parents[5] / "postgres/scripts/createProcessingDB.sql"
        # Use the production table and expression-index definitions in a random schema.
        ddl = ddl_path.read_text().replace(
            '"BPDATA"', sql.Identifier(cls.schema).as_string()
        )
        with psycopg.connect(cls.conninfo, autocommit=True) as connection:
            with connection.transaction():
                connection.execute(ddl)
                connection.execute(
                    sql.SQL("CREATE SCHEMA {}").format(
                        sql.Identifier(cls.summary_schema)
                    )
                )
                connection.execute(
                    sql.SQL(
                        """CREATE TABLE {} (
                    "ID_OUTBOX" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    "NA_SCOPE_TYPE" varchar(32) NOT NULL, "NA_SCOPE_VALUE" varchar(64) NOT NULL,
                    "NA_SOURCE_HANDLER" varchar(64), "NA_REASON" varchar(64),
                    "DT_CREATED_AT" timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
                    UNIQUE ("NA_SCOPE_TYPE", "NA_SCOPE_VALUE"))
                """
                    ).format(sql.Identifier(cls.summary_schema, "SUMMARY_OUTBOX"))
                )

    @classmethod
    def _drop_schemas(cls) -> None:
        """Drop only the generated schemas in the explicitly selected test database.

        Args:
            None.
        Returns:
            None.
        Raises:
            psycopg.Error: If fixture cleanup fails.
        """
        cls.handler.close()
        with psycopg.connect(cls.conninfo, autocommit=True) as connection:
            for name in (cls.schema, cls.summary_schema):
                connection.execute(
                    sql.SQL("DROP SCHEMA IF EXISTS {} CASCADE").format(
                        sql.Identifier(name)
                    )
                )

    def setUp(self) -> None:
        """Reset isolated fixtures and create one addressable host for each test.

        Args:
            None.
        Returns:
            None.
        Raises:
            psycopg.Error: If fixture reset fails.
        """
        self.addCleanup(self.handler.close)
        self.handler._execute(
            sql.SQL("TRUNCATE {}, {}, {}, {}, {} RESTART IDENTITY CASCADE").format(
                *(
                    sql.Identifier(self.schema, name)
                    for name in ("HOST", "HOST_TASK", "FILE_TASK", "FILE_TASK_HISTORY")
                ),
                sql.Identifier(self.summary_schema, "SUMMARY_OUTBOX"),
            )
        )
        self.handler.host_upsert(
            ID_HOST=1,
            NA_HOST_ADDRESS="unit-test",
            NA_HOST_NAME="CWSM_TEST",
            IS_BUSY=False,
            IS_OFFLINE=False,
        )
        self.created = datetime(2025, 2, 3, 4, 5)
        self.file = FileMetadata(
            "/source/a.zip",
            "/source",
            "a.zip",
            ".zip",
            20,
            self.created,
            self.created,
            None,
            "owner",
            "group",
            "rw",
        )

    def test_connectivity_keeps_null_ordering_and_excludes_blank_addresses(
        self,
    ) -> None:
        """Preserve the connectivity snapshot's selection and ordering through CRUD.

        Args:
            None.
        Returns:
            None.
        """
        hosts = [
            {"ID_HOST": 2, "NA_HOST_ADDRESS": None},
            {"ID_HOST": 3, "NA_HOST_ADDRESS": ""},
            {"ID_HOST": 4, "NA_HOST_ADDRESS": "   "},
            {"ID_HOST": 5, "NA_HOST_ADDRESS": "never-checked", "IS_OFFLINE": 0},
            {
                "ID_HOST": 6,
                "NA_HOST_ADDRESS": "older",
                "IS_OFFLINE": 0,
                "DT_LAST_CHECK": self.created,
            },
            {"ID_HOST": 7, "NA_HOST_ADDRESS": "offline", "IS_OFFLINE": 1},
            {"ID_HOST": 8, "NA_HOST_ADDRESS": "unknown", "IS_OFFLINE": None},
        ]
        for data in hosts:
            self.handler.host_upsert(**data)
        self.handler.host_update(1, DT_LAST_CHECK=datetime(2026, 1, 1), IS_BUSY=1)
        rows = self.handler.host_list_for_connectivity_check()
        self.assertEqual([row["ID_HOST"] for row in rows], [8, 5, 6, 1, 7])

