    def test_converted_zip_dedup_keeps_path_identity_and_extension_case(self) -> None:
        """Ignore completed ZIP conversions even after source size changes.

        Args:
            None.
        Returns:
            None.
        """
        self.handler.file_task_history_create(
            host_id=1, task_type=3, task_status=0, file_metadata=[self.file]
        )
