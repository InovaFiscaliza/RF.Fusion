class IntegrationHandler(DbHandler):
    """Use isolated SQL tables without declaring their schema in Python."""



class PostgresIntegrationTests(unittest.TestCase):
    """Verify SQL and transaction semantics against an isolated PostgreSQL.

    Attributes:
        conninfo (str): Explicit test-only connection settings, never logged.
        schema (str): Random schema name created and removed for this test class.
        handler (IntegrationHandler): Shared test session closed by class cleanup.
    """

    @classmethod
    def setUpClass(cls) -> None:
        """Require a disposable database and create a uniquely named schema.

        Args:
            None.
        Returns:
            None.
        Raises:
            unittest.SkipTest: If no explicit test connection was supplied.
            ValueError: If the database name lacks the rffusion_test_ prefix.
            psycopg.Error: If test schema creation fails.
        """
        cls.conninfo = os.environ.get("RFFUSION_TEST_PG_CONNINFO", "")
        if not cls.conninfo:
            raise unittest.SkipTest("RFFUSION_TEST_PG_CONNINFO is not configured.")
        settings = conninfo_to_dict(cls.conninfo)
        if not settings.get("dbname", "").startswith("rffusion_test_"):
            raise ValueError(
                "Integration requires a disposable rffusion_test_* database."
            )
        cls.schema = f"TEST_{uuid4().hex}"
        cls.handler = IntegrationHandler(
            cls.schema, MagicMock(spec=logging_utils.log), conninfo=cls.conninfo
        )
        cls.addClassCleanup(cls.handler.close)
        cls.handler._execute(
            sql.SQL("CREATE SCHEMA {}").format(sql.Identifier(cls.schema))
        )
        cls.addClassCleanup(cls._drop_schema)
        cls.handler._execute(
            sql.SQL(
                """
            CREATE TABLE {}."SAMPLE" (
                "ID" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                "NAME" text NOT NULL UNIQUE,
                "ACTIVE" boolean,
                "UPDATED" timestamp without time zone
            )
        """
            ).format(sql.Identifier(cls.schema))
        )

    @classmethod
    def _drop_schema(cls) -> None:
        """Remove only this class's generated schema through a fresh session.

        Args:
            None.
        Returns:
            None.
        Raises:
            psycopg.Error: If test cleanup fails.
        """
        cls.handler.close()
        with psycopg.connect(cls.conninfo, autocommit=True) as connection:
            connection.execute(
                sql.SQL("DROP SCHEMA {} CASCADE").format(sql.Identifier(cls.schema))
            )

    def setUp(self) -> None:
        """Reset rows inside the generated test schema.

        Args:
            None.
        Returns:
            None.
        """
        self.handler._execute(
            sql.SQL('TRUNCATE {}."SAMPLE" RESTART IDENTITY').format(
                sql.Identifier(self.schema)
            )
        )
        self.addCleanup(self.handler.close)

    def test_crud_returning_nulls_and_timestamps(self) -> None:
        """Run CRUD with quoted names, generated IDs, booleans, and NULL values.

        Args:
            None.
        Returns:
            None.
        """
        row = self.handler._insert_row(
            "SAMPLE", {"NAME": "one", "ACTIVE": None}, returning=("ID", "NAME")
        )
        self.assertEqual(row, {"ID": 1, "NAME": "one"})
        self.assertEqual(len(self.handler._select_batch("SAMPLE", {"ACTIVE": None})), 1)
        self.assertEqual(
            self.handler._update_row(
                "SAMPLE", {"ACTIVE": True}, {"ID": 1}, touch_field="UPDATED"
            ),
            1,
        )
        result = self.handler._select_batch("SAMPLE")[0]
        self.assertIs(result["ACTIVE"], True)
        self.assertIsNotNone(result["UPDATED"])
        self.assertEqual(self.handler._select_batch("SAMPLE", limit=0), [])
        self.assertEqual(self.handler._delete_batch("SAMPLE", {"ID__in": [1]}), 1)
        self.assertEqual(self.handler._select_batch("SAMPLE"), [])

    def test_unknown_identifiers_raise_original_postgres_errors(self) -> None:
        """Delegate SQL name validation without weakening identifier quoting.

        Args:
            None.
        Returns:
            None.
        """
        operations = (
            lambda: self.handler._select_batch("SAMPLE", columns=("MISSING",)),
            lambda: self.handler._select_batch("SAMPLE", where={"MISSING": 1}),
            lambda: self.handler._select_batch("SAMPLE", order_by=(("MISSING", "ASC"),)),
            lambda: self.handler._insert_row("SAMPLE", {"MISSING": 1}),
            lambda: self.handler._insert_row("SAMPLE", {"NAME": "one"}, returning=("MISSING",)),
            lambda: self.handler._insert_batch("SAMPLE", [{"MISSING": 1}]),
            lambda: self.handler._update_batch("SAMPLE", {"MISSING": 1}, {"ID": 1}),
            lambda: self.handler._delete_batch("SAMPLE", {"MISSING": 1}),
            lambda: self.handler._upsert_row("SAMPLE", {"NAME": "one", "MISSING": 1}, conflict_columns=("NAME",)),
            lambda: self.handler._select_aggregate("SAMPLE", {"N": ("count", "MISSING", None)}),
            lambda: self.handler._select_batch("SAMPLE", columns=('NAME"; DROP TABLE "SAMPLE"; --',)),
        )
        for operation in operations:
            with self.subTest(operation=operation):
                with self.assertRaises(psycopg.errors.UndefinedColumn) as raised:
                    operation()
                self.assertEqual(raised.exception.sqlstate, "42703")
        for table in ("MISSING", 'SAMPLE"; DROP TABLE "SAMPLE"; --'):
            with self.subTest(table=table):
                with self.assertRaises(psycopg.errors.UndefinedTable) as raised:
                    self.handler._select_batch(table)
                self.assertEqual(raised.exception.sqlstate, "42P01")
        self.assertEqual(self.handler._select_batch("SAMPLE"), [])

    def test_new_columns_work_without_python_schema_changes(self) -> None:
        """Use a new SQL column immediately and keep explicit failures caller-owned.

        Args:
            None.
        Returns:
            None.
        """
        self.handler.begin_transaction()
        try:
            self.handler._execute(sql.SQL('ALTER TABLE {} ADD COLUMN "NOTE" text').format(sql.Identifier(self.schema, "SAMPLE")))
            self.handler._insert_row("SAMPLE", {"NAME": "one", "NOTE": "added in SQL"})
            self.assertEqual(self.handler._select_row("SAMPLE", {"ID": 1})["NOTE"], "added in SQL")
            self.handler._update_row("SAMPLE", {"NOTE": "updated"}, {"ID": 1})
            self.assertEqual(self.handler._select_batch("SAMPLE", columns=("NOTE",)), [{"NOTE": "updated"}])
            with self.assertRaises(psycopg.errors.UndefinedColumn):
                self.handler._select_batch("SAMPLE", columns=("MISSING",))
            self.assertTrue(self.handler.in_transaction)
            with self.assertRaises(psycopg.errors.InFailedSqlTransaction):
                self.handler._select_batch("SAMPLE")
        finally:
            self.handler.rollback()
        self.assertEqual(self.handler._select_batch("SAMPLE"), [])

    def test_row_operations_use_database_unique_identity_without_declarations(self) -> None:
        """Use an alternate unique key and conditional writes with engine errors.

        Args:
            None.
        Returns:
            None.
        """
        self.handler._insert_row("SAMPLE", {"ID": 1, "NAME": "one", "ACTIVE": True})
        self.assertEqual(self.handler._select_row("SAMPLE", {"NAME": "one"})["ID"], 1)
        self.assertEqual(self.handler._update_row("SAMPLE", {"ACTIVE": False}, {"NAME": "one", "ACTIVE": False}), 0)
        self.assertEqual(self.handler._update_row("SAMPLE", {"ACTIVE": False}, {"NAME": "one", "ACTIVE": True}), 1)
        with self.assertRaises(psycopg.errors.UniqueViolation) as raised:
            self.handler._insert_row("SAMPLE", {"ID": 1, "NAME": "two"})
        self.assertEqual(raised.exception.sqlstate, "23505")
        for operation in (
            lambda: self.handler._select_row("SAMPLE", {"MISSING": 1}),
            lambda: self.handler._update_row("SAMPLE", {"ACTIVE": True}, {"MISSING": 1}),
            lambda: self.handler._delete_row("SAMPLE", {"MISSING": 1}),
        ):
            with self.assertRaises(psycopg.errors.UndefinedColumn):
                operation()
        self.assertEqual(self.handler._delete_row("SAMPLE", {"NAME": "one"}), 1)
        self.assertIsNone(self.handler._select_row("SAMPLE", {"NAME": "one"}))

    def test_composite_identity_is_defined_only_in_postgres(self) -> None:
        """Operate on a composite SQL key without registering it in the handler.

        Args:
            None.
        Returns:
            None.
        """
        self.handler.begin_transaction()
        try:
            self.handler._execute(sql.SQL('CREATE TABLE {} ("A" int, "B" int, "VALUE" text, PRIMARY KEY ("A", "B"))').format(sql.Identifier(self.schema, "PAIR")))
            self.handler._insert_batch("PAIR", [{"A": 1, "B": 2, "VALUE": "first"}, {"A": 1, "B": 3, "VALUE": "second"}])
            self.assertEqual(self.handler._select_row("PAIR", {"B": 2, "A": 1})["VALUE"], "first")
            self.assertEqual(self.handler._update_row("PAIR", {"VALUE": "changed"}, {"A": 1, "B": 2}), 1)
            self.assertEqual(self.handler._select_row("PAIR", {"A": 1, "B": 3})["VALUE"], "second")
            self.assertEqual(self.handler._delete_row("PAIR", {"B": 2, "A": 1}), 1)
            self.assertEqual(len(self.handler._select_batch("PAIR")), 1)
        finally:
            self.handler.rollback()

    def test_locked_select_blocks_another_session_until_rollback(self) -> None:
        """Hold actual PostgreSQL row locks until the owning transaction completes.

        Args:
            None.
        Returns:
            None.
        """
        self.handler._insert_row(table="SAMPLE", data={"ID": 1, "NAME": "locked"})
        self.handler.begin_transaction()
        self.handler._select_batch(table="SAMPLE", where={"ID": 1}, for_update=True)
        query = sql.SQL('SELECT "ID" FROM {} WHERE "ID" = %s FOR UPDATE NOWAIT').format(
            sql.Identifier(self.schema, "SAMPLE")
        )
        with psycopg.connect(self.conninfo, autocommit=True) as contender:
            with self.assertRaises(psycopg.errors.LockNotAvailable):
                contender.execute(query, (1,))
            self.handler.rollback()
            self.assertEqual(contender.execute(query, (1,)).fetchone(), (1,))

    def test_text_filters_and_null_ordering_match_postgres_semantics(self) -> None:
        """Keep spaces, case variants, and NULL placement consistent with the engine.

        Args:
            None.
        Returns:
            None.
        """
        self.handler._insert_batch(
            table="SAMPLE",
            data=[
                {"NAME": "  ", "UPDATED": None},
                {"NAME": "sample.MAT", "UPDATED": datetime(2025, 1, 1)},
                {"NAME": "other.mat", "UPDATED": None},
            ],
        )
        rows = self.handler._select_batch(
            table="SAMPLE",
            where={"NAME__trim_ne": "", "NAME__ilike": "%.mat"},
            order_by=(("UPDATED", "ASC NULLS FIRST"),),
        )
        self.assertEqual([row["NAME"] for row in rows], ["other.mat", "sample.MAT"])

    def test_row_and_batch_crud_have_distinct_cardinality(self) -> None:
        """Exercise primary-key row operations and filtered batch writes.

        Args:
            None.
        Returns:
            None.
        """
        self.assertEqual(
            self.handler._insert_batch(
                table="SAMPLE",
                data=[
                    {"NAME": "one", "ACTIVE": True},
                    {"ACTIVE": True, "NAME": "two"},
                ],
                batch_size=1,
            ),
            2,
        )
        row = self.handler._select_row("SAMPLE", {"ID": 1})
        self.assertEqual(row["NAME"], "one")
        self.assertIsNone(self.handler._select_row("SAMPLE", {"ID": 99}))
        self.assertEqual(
            self.handler._update_row("SAMPLE", {"NAME": "renamed"}, {"ID": 1}), 1
        )
        self.assertEqual(
            self.handler._update_batch("SAMPLE", {"ACTIVE": False}, {"ACTIVE": True}), 2
        )
        self.assertEqual(self.handler._delete_row("SAMPLE", {"ID": 1}), 1)
        self.assertEqual(self.handler._delete_batch("SAMPLE", {"ACTIVE": False}), 1)
        self.assertEqual(self.handler._select_batch("SAMPLE"), [])

    def test_insert_batch_rolls_back_previous_chunks_on_duplicate_failure(self) -> None:
        """Keep earlier INSERT chunks uncommitted if a later row violates uniqueness.

        Args:
            None.
        Returns:
            None.
        """
        with self.assertRaises(psycopg.errors.UniqueViolation):
            self.handler._insert_batch(
                table="SAMPLE",
                data=[
                    {"NAME": "duplicate"},
                    {"NAME": "duplicate"},
                ],
                batch_size=1,
            )
        self.assertEqual(self.handler._select_batch("SAMPLE"), [])

    def test_postgres_conflict_counts_and_key_only_insert(self) -> None:
        """Confirm conflict targets and counts against the actual engine.

        Args:
            None.
        Returns:
            None.
        """
        self.assertEqual(
            self.handler._upsert_row(
                "SAMPLE", {"NAME": "one", "ACTIVE": True}, conflict_columns=("NAME",)
            ),
            1,
        )
        self.assertEqual(
            self.handler._upsert_row(
                "SAMPLE", {"NAME": "one", "ACTIVE": False}, conflict_columns=("NAME",)
            ),
            1,
        )
        self.assertEqual(
            self.handler._upsert_row(
                "SAMPLE", {"NAME": "one"}, conflict_columns=("NAME",)
            ),
            0,
        )
        self.assertIs(self.handler._select_batch("SAMPLE")[0]["ACTIVE"], False)

    def test_failed_later_chunk_rolls_back_the_entire_batch(self) -> None:
        """Prove that a later constraint error cannot leave earlier chunks saved.

        Args:
            None.
        Returns:
            None.
        """
        with self.assertRaises(psycopg.errors.NotNullViolation):
            self.handler._upsert_batch(
                table="SAMPLE",
                data=[
                    {"ID": 1, "NAME": "valid"},
                    {"ID": 2, "NAME": None},
                ],
                conflict_columns=("ID",),
                batch_size=1,
            )
        self.assertEqual(self.handler._select_batch("SAMPLE"), [])

    def test_aborted_transaction_requires_rollback_and_retains_no_rows(self) -> None:
        """Verify PostgreSQL's aborted transaction state and explicit recovery.

        Args:
            None.
        Returns:
            None.
        """
        self.handler.begin_transaction()
        self.handler._insert_row("SAMPLE", {"NAME": "valid"})
        with self.assertRaises(psycopg.errors.NotNullViolation):
            self.handler._insert_row("SAMPLE", {"NAME": None})
        with self.assertRaises(RuntimeError):
            self.handler.commit()
        self.handler.rollback()
        self.assertEqual(self.handler._select_batch("SAMPLE"), [])

    def test_other_session_cannot_see_uncommitted_rows(self) -> None:
        """Keep related writes invisible to another reader until caller commit.

        Args:
            None.
        Returns:
            None.
        """
        reader = IntegrationHandler(
            self.schema,
            MagicMock(spec=logging_utils.log),
            conninfo=self.conninfo,
            reuse_connection=False,
        )
        self.addCleanup(reader.close)
        self.handler.begin_transaction()
        self.handler._insert_row("SAMPLE", {"NAME": "uncommitted"})
        self.assertEqual(reader._select_batch("SAMPLE"), [])
        self.handler.commit()
        self.assertEqual(len(reader._select_batch("SAMPLE")), 1)


