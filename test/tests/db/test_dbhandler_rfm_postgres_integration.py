    def test_site_type_repair_is_repeatable_and_rejects_conflicting_catalog(self) -> None:
        """Repair missing types while preserving catalog meaning and sequence.

        Args:
            None.
        Returns:
            None.
        """
        schema = "TEST_TYPE_" + uuid4().hex
        target = sql.Identifier(schema, "DIM_SITE_TYPE")
        repair = (APP_ROOT.parents[5] / "postgres/scripts/ensureSiteTypes.sql").read_text()
        repair = repair.replace('"RFDATA"', sql.Identifier(schema).as_string())
        with psycopg.connect(self.conninfo, autocommit=True) as connection:
            connection.execute(sql.SQL("CREATE SCHEMA {}").format(sql.Identifier(schema)))
            try:
                connection.execute(sql.SQL(
                    'CREATE TABLE {} ("ID_TYPE" integer GENERATED BY DEFAULT AS IDENTITY '
                    'PRIMARY KEY, "NA_TYPE" varchar(50))'
                ).format(target))
                connection.execute(repair)
                connection.execute(sql.SQL(
                    'SELECT setval(pg_get_serial_sequence(%s, %s), 100, true)'
                ), (target.as_string(), "ID_TYPE"))
                connection.execute(repair)
                self.assertEqual(connection.execute(sql.SQL(
                    'SELECT "ID_TYPE", "NA_TYPE" FROM {} ORDER BY "ID_TYPE"'
                ).format(target)).fetchall(), [(1, "Fixed"), (2, "Mobile")])
                generated = connection.execute(sql.SQL(
                    'INSERT INTO {} ("NA_TYPE") VALUES (%s) RETURNING "ID_TYPE"'
                ).format(target), ("Other",)).fetchone()[0]
                self.assertGreater(generated, 100)
                connection.execute(sql.SQL(
                    'UPDATE {} SET "NA_TYPE" = chr(39) || "NA_TYPE" || chr(39) '
                    'WHERE "ID_TYPE" IN (1, 2)'
                ).format(target))
                connection.execute(repair)
                self.assertEqual(connection.execute(sql.SQL(
                    'SELECT "ID_TYPE", "NA_TYPE" FROM {} WHERE "ID_TYPE" IN (1, 2) '
                    'ORDER BY "ID_TYPE"'
                ).format(target)).fetchall(), [(1, "'Fixed'"), (2, "'Mobile'")])
                for type_id, label in ((1, "'Fixed'"), (2, "'Mobile'")):
                    with self.subTest(type_id=type_id):
                        connection.execute(sql.SQL(
                            'UPDATE {} SET "NA_TYPE" = %s WHERE "ID_TYPE" = %s'
                        ).format(target), ("Unexpected", type_id))
                        with self.assertRaises(psycopg.errors.RaiseException):
                            connection.execute(repair)
                        connection.rollback()
                        self.assertEqual(connection.execute(sql.SQL(
                            'SELECT "NA_TYPE" FROM {} WHERE "ID_TYPE" = %s'
                        ).format(target), (type_id,)).fetchone()[0], "Unexpected")
                        connection.execute(sql.SQL(
                            'UPDATE {} SET "NA_TYPE" = %s WHERE "ID_TYPE" = %s'
                        ).format(target), (label, type_id))
            finally:
                connection.execute(sql.SQL("DROP SCHEMA {} CASCADE").format(sql.Identifier(schema)))

