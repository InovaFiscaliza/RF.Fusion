    def test_failed_outbox_does_not_abort_caller_transaction(self) -> None:
        """Keep analytical writes usable after a missing outbox rolls back its savepoint.

        Args:
            None.
        Returns:
            None.
        """
        from db import dbHandlerBase as base_module

        handler = self.handler
        handler.begin_transaction()
        try:
            file_id = handler.insert_file("rfeye", "/transaction", "x.zip", "HOST")
            with patch.object(
                base_module.k, "SUMMARY_DATABASE_NAME", "MISSING_OUTBOX_SCHEMA"
            ):
                handler._summary_publish_scope(site_ids=(1,), reason="test")
            self.assertTrue(handler.in_transaction)
            self.assertIsNotNone(
                handler._select_row(
                    table="DIM_SPECTRUM_FILE", where={"ID_FILE": file_id}
                )
            )
            handler.rollback()
            self.assertIsNone(
                handler._select_row(
                    table="DIM_SPECTRUM_FILE", where={"ID_FILE": file_id}
                )
            )
        finally:
            if handler.in_transaction:
                handler.rollback()
