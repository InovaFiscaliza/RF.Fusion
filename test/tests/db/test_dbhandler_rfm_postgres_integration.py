    def test_file_spectrum_growth_lineage_and_outbox(self) -> None:
        """Preserve spectrum identities and avoid deleting shared lineage.

        Args:
            None.
        Returns:
            None.
        """
        from datetime import datetime, timedelta

        h = self.handler
        procedure = h.insert_procedure("sweep")
        detector = h.insert_detector_type("peak")
        trace = h.insert_trace_type("average")
        unit = h.insert_measure_unit("dBm")
        equipment = h.get_or_create_spectrum_equipment("rfeye unit")
        file_id = h.insert_file("rfeye", "/host", "a.zip", "HOST", VL_FILE_SIZE_KB=10)
        self.assertEqual(
            file_id,
            h.insert_file("rfeye", "/host", "a.zip", "HOST", VL_FILE_SIZE_KB=20),
        )
        repository = h.insert_file("rfeye", "/repo", "a.mat", "SERVER")
        shared = h.insert_file("rfeye", "/shared", "b.mat", "SERVER")
        start = datetime(2026, 1, 1)
        spectrum = {
            "id_site": 1,
            "id_equipment": equipment,
            "id_procedure": procedure,
            "id_detector_type": detector,
            "id_trace_type": trace,
            "id_measure_unit": unit,
            "nu_freq_start": 100,
            "nu_freq_end": 200,
            "dt_time_start": start,
            "dt_time_end": start + timedelta(hours=1),
            "nu_trace_length": 10,
            "nu_trace_count": 1,
            "js_metadata": {"source": "test"},
        }
        spectrum_id = h.insert_spectrum(spectrum)
        spectrum["dt_time_end"] = start + timedelta(hours=2)
        self.assertEqual(h.insert_spectrum(spectrum), spectrum_id)
        h.insert_bridge_spectrum_file([spectrum_id], [file_id, repository, shared])
        result = h.reset_reprocessed_file_lineage(
            host_volume="HOST",
            host_path="/host",
            host_file="a.zip",
            repository_volume="SERVER",
            repository_path="/repo",
            repository_file="a.mat",
        )
        self.assertEqual(result["removed_file_links"], 2)
        self.assertEqual(result["removed_spectra"], 0)
        self.assertIsNotNone(
            h._select_row(table="FACT_SPECTRUM", where={"ID_SPECTRUM": spectrum_id})
        )
        with psycopg.connect(self.conninfo) as connection:
            scopes = connection.execute(
                sql.SQL('SELECT "NA_SCOPE_TYPE", "NA_SCOPE_VALUE" FROM {}').format(
                    sql.Identifier(self.summary_schema, "SUMMARY_OUTBOX")
                )
            ).fetchall()
        self.assertIn(("equipment", str(equipment)), scopes)
        self.assertIn(("site", "1"), scopes)
        result = h.reset_reprocessed_file_lineage(
            host_volume="SERVER",
            host_path="/shared",
            host_file="b.mat",
            repository_volume="SERVER",
            repository_path="/missing",
            repository_file="none.mat",
        )
        self.assertEqual(result["removed_file_links"], 1)
        self.assertEqual(result["removed_spectra"], 1)
        self.assertIsNone(
            h._select_row(table="FACT_SPECTRUM", where={"ID_SPECTRUM": spectrum_id})
        )

